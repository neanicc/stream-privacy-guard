#!/usr/bin/env python3
"""Generates fold_table.inc, the character folding table for policy text.

Each listed code point maps to casefold(NFKC(c)) with combining marks removed
and a few undecomposable Latin letters spelled out (LATIN_EXTRA), applied until
nothing changes. That folds compatibility forms (fullwidth
letters, ligatures, circled and mathematical letters, superscripts), case and
diacritics, so that "ＪＯＳÉ", "𝐉𝐨𝐬𝐞" and "jose" fold to the same text. Only
the blocks below are covered; code points outside them pass through unchanged
(ASCII upper case is folded in normalize.cpp).

Usage: make_fold_table.py [output path]. The table depends on the Unicode
version of the interpreter's unicodedata, which the output records.
"""

import pathlib
import sys
import unicodedata

# Blocks whose text OCR or a watch-list entry plausibly contains.
RANGES = [
    (0x00A0, 0x024F),  # Latin-1 Supplement, Latin Extended-A and -B
    (0x0300, 0x036F),  # Combining Diacritical Marks
    (0x0370, 0x03FF),  # Greek and Coptic
    (0x0400, 0x04FF),  # Cyrillic
    (0x1AB0, 0x1AFF),  # Combining Diacritical Marks Extended
    (0x1DC0, 0x1DFF),  # Combining Diacritical Marks Supplement
    (0x1E00, 0x1EFF),  # Latin Extended Additional
    (0x2070, 0x209F),  # Superscripts and Subscripts
    (0x20D0, 0x20FF),  # Combining Diacritical Marks for Symbols
    (0x2100, 0x218F),  # Letterlike Symbols, Number Forms
    (0x2460, 0x24FF),  # Enclosed Alphanumerics
    (0xFB00, 0xFB06),  # Latin ligatures
    (0xFE20, 0xFE2F),  # Combining Half Marks
    (0xFF00, 0xFFEF),  # Halfwidth and Fullwidth Forms
    (0x1D400, 0x1D7FF),  # Mathematical Alphanumeric Symbols
    (0x1F100, 0x1F1FF),  # Enclosed Alphanumeric Supplement
]

# Latin letters that have no decomposition but that OCR and ASCII keyboards
# spell with base letters.
LATIN_EXTRA = str.maketrans({"æ": "ae", "œ": "oe", "ø": "o", "ð": "d", "þ": "th", "ł": "l", "đ": "d", "ħ": "h", "ı": "i", "ŧ": "t"})


def fold_once(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).casefold().translate(LATIN_EXTRA)
    text = "".join(c for c in unicodedata.normalize("NFKD", text) if unicodedata.category(c) != "Mn")
    return unicodedata.normalize("NFC", text)


def fold(text: str) -> str:
    while True:
        folded = fold_once(text)
        if folded == text:
            return text
        text = folded


def build() -> list[tuple[int, int, str]]:
    mapping: dict[int, str] = {}
    for first, last in RANGES:
        for cp in range(first, last + 1):
            if unicodedata.category(chr(cp)) in ("Cn", "Cs"):
                continue
            out = fold(chr(cp))
            if out != chr(cp):
                mapping[cp] = out
    # Merge consecutive code points into ranges: deletions (empty output) and
    # single characters whose output also steps by one.
    entries: list[tuple[int, int, str]] = []
    for cp in sorted(mapping):
        out = mapping[cp]
        if entries:
            first, last, start = entries[-1]
            prev = mapping[last]
            if cp == last + 1 and (
                (out == "" and prev == "")
                or (len(out) == 1 and len(prev) == 1 and ord(out) == ord(prev) + 1 and len(start) == 1)
            ):
                entries[-1] = (first, cp, start)
                continue
        entries.append((cp, cp, out))
    return entries


def literal(text: str) -> str:
    parts = []
    for c in text:
        if 0x20 <= ord(c) < 0x7F and c not in '"\\?':
            parts.append(c)
        else:
            parts.append(f"\\U{ord(c):08X}")
    return 'U"' + "".join(parts) + '"'


def main() -> int:
    out_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).with_name("fold_table.inc")
    entries = build()
    lines = [
        "// Generated by core/src/policy/make_fold_table.py from Python unicodedata",
        f"// (Unicode {unicodedata.unidata_version}). Do not edit by hand.",
        "// {first, last, out}: first..last fold to out. A range with a one-character",
        "// out steps the output with the code point; an empty out deletes the range.",
    ]
    row: list[str] = []
    for first, last, out in entries:
        row.append(f"{{0x{first:X}, 0x{last:X}, {literal(out)}}},")
        if len(row) == 4:
            lines.append(" ".join(row))
            row = []
    if row:
        lines.append(" ".join(row))
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} entries to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
